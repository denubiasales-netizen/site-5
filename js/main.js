let lang = localStorage.getItem('lang') || 'pt';

function applyLang() {
  lang = localStorage.getItem('lang') || 'pt';
  document.documentElement.setAttribute('lang', lang);
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const k = el.dataset.i18n;
    if (I18N[lang][k] !== undefined) el.textContent = I18N[lang][k];
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const k = el.dataset.i18nPh;
    if (I18N[lang][k] !== undefined) el.setAttribute('placeholder', I18N[lang][k]);
  });
  document.querySelectorAll('[data-i18n-alt]').forEach(el => {
    const k = el.dataset.i18nAlt;
    if (I18N[lang][k] !== undefined) el.setAttribute('alt', I18N[lang][k]);
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const k = el.dataset.i18nHtml;
    if (I18N[lang][k] !== undefined) el.innerHTML = I18N[lang][k];
  });
  document.querySelectorAll('[data-lang]').forEach(b => b.classList.toggle('is-active', b.dataset.lang === lang));
  document.querySelectorAll('[data-lang]').forEach(b => b.setAttribute('aria-pressed', String(b.dataset.lang === lang)));
  if (I18N[lang].meta_title) document.title = I18N[lang].meta_title;
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc && I18N[lang].meta_desc) metaDesc.setAttribute('content', I18N[lang].meta_desc);
}

document.querySelectorAll('[data-lang]').forEach(b => b.addEventListener('click', () => {
  localStorage.setItem('lang', b.dataset.lang);
  applyLang();
}));

document.addEventListener('DOMContentLoaded', function () {
  const header = document.getElementById('site-header');
  const navToggle = document.getElementById('nav-toggle');
  const mainNav = document.getElementById('main-nav');

  function onScroll() {
    header.classList.toggle('is-scrolled', window.scrollY > 10);
  }

  window.addEventListener('scroll', onScroll, { passive: true });
  onScroll();

  function closeMenu() {
    mainNav.classList.remove('is-open');
    navToggle.classList.remove('is-open');
    navToggle.setAttribute('aria-expanded', 'false');
  }

  navToggle.addEventListener('click', function () {
    const open = mainNav.classList.toggle('is-open');
    navToggle.classList.toggle('is-open', open);
    navToggle.setAttribute('aria-expanded', String(open));
  });

  mainNav.querySelectorAll('a').forEach(function (link) {
    link.addEventListener('click', closeMenu);
  });

  document.addEventListener('keydown', function (e) {
    if (e.key === 'Escape') closeMenu();
  });

  const revealEls = document.querySelectorAll('.reveal');

  if ('IntersectionObserver' in window) {
    const io = new IntersectionObserver(function (entries) {
      entries.forEach(function (entry) {
        if (entry.isIntersecting) {
          entry.target.classList.add('is-visible');
          io.unobserve(entry.target);
        }
      });
    }, { threshold: 0.12, rootMargin: '0px 0px -40px 0px' });

    revealEls.forEach(function (el) {
      io.observe(el);
    });
  } else {
    revealEls.forEach(function (el) {
      el.classList.add('is-visible');
    });
  }

  const filterState = { type: 'all', beds: 'any', price: 'any' };
  const cards = Array.prototype.slice.call(document.querySelectorAll('.prop-card'));
  const noResults = document.getElementById('no-results');
  const chips = document.querySelectorAll('#property-filters .chip');

  function applyFilters() {
    let count = 0;

    cards.forEach(function (card) {
      const type = card.dataset.type;
      const beds = parseInt(card.dataset.beds, 10);
      const price = parseFloat(card.dataset.price);
      let show = true;

      if (filterState.type !== 'all' && type !== filterState.type) show = false;

      if (show && filterState.beds !== 'any' && beds < parseInt(filterState.beds, 10)) show = false;

      if (show) {
        if (filterState.price === 'u750' && price > 0.75) {
          show = false;
        } else if (filterState.price === '750_1_5' && (price <= 0.75 || price > 1.5)) {
          show = false;
        } else if (filterState.price === '1_5' && price <= 1.5) {
          show = false;
        }
      }

      card.hidden = !show;
      if (show) count += 1;
    });

    noResults.hidden = count > 0;
  }

  chips.forEach(function (chip) {
    chip.addEventListener('click', function () {
      const group = chip.dataset.type ? 'type' : (chip.dataset.beds ? 'beds' : 'price');

      document.querySelectorAll('#property-filters [data-' + group + ']').forEach(function (c) {
        c.classList.remove('is-active');
      });

      chip.classList.add('is-active');
      filterState[group] = chip.dataset.type || chip.dataset.beds || chip.dataset.price;
      applyFilters();
    });
  });

  const heroSearch = document.getElementById('hero-search');
  heroSearch.addEventListener('submit', function (e) {
    e.preventDefault();
    document.getElementById('properties').scrollIntoView({ behavior: 'smooth' });
  });

  const contactForm = document.getElementById('contact-form');
  const formSuccess = document.getElementById('form-success');

  contactForm.addEventListener('submit', function (e) {
    e.preventDefault();
    formSuccess.classList.add('is-visible');
    contactForm.reset();
    window.setTimeout(function () {
      formSuccess.classList.remove('is-visible');
    }, 6000);
  });

  document.getElementById('footer-year').textContent = new Date().getFullYear();

  applyLang();
});